import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = resolve(fileURLToPath(new URL('.', import.meta.url)));
const WEB_ROOT = resolve(SCRIPT_DIR, '../..');
const APP_ROOT = resolve(WEB_ROOT, 'app/organizations/[organizationId]');
const OUTPUT = resolve(WEB_ROOT, '../../docs/audits/ui-surfaces.generated.md');

const patterns = [
  ['WorkspaceHome', /\bWorkspaceHome\b/],
  ['PageHeader', /\bPageHeader\b/],
  ['CollectionHeader', /\bCollectionHeader\b/],
  ['AppPage', /\bAppPage\b/],
  ['CollectionView', /\bCollectionView\b/],
  ['ViewNav', /\bViewNav\b/],
  ['DataTable', /\bDataTable\b/],
  ['WidgetGrid', /\bWidgetGrid\b/],
  ['EmptyState', /\bEmptyState\b/],
];

function walk(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) return walk(path);
    return entry.name === 'page.tsx' ? [path] : [];
  });
}

function routeFrom(path) {
  return relative(APP_ROOT, path)
    .replaceAll('\\', '/')
    .replace(/\/page\.tsx$/, '')
    .replace(/\([^/]+\)\//g, '');
}

function scope(route) {
  if (route.startsWith('platform/')) return 'Platform';
  if (route.startsWith('settings/')) return 'Settings';
  if (route.startsWith('library/')) return 'Library';
  if (route === 'home') return 'Global Home';
  if (/^(sales|customers(?:\/|$))/.test(route)) return 'CRM';
  if (/^(comms|calls)(?:\/|$)/.test(route)) return 'Communications';
  if (/^finance(?:\/|$)/.test(route)) return 'Finance';
  if (/^automations(?:\/|$)/.test(route)) return 'Automations';
  if (/^(field|work|schedule|resources|locations|assets)(?:\/|$)/.test(route)) return 'Field';
  if (/^studio(?:\/|$)/.test(route)) return 'Studio';
  if (/^insights(?:\/|$)/.test(route)) return 'Insights';
  if (/^integrations(?:\/|$)/.test(route)) return 'Connections';
  return 'Cross-cutting / legacy';
}

function archetype(route, source) {
  if (/\bWorkspaceHome\b/.test(source)) return 'Workspace Home';
  if (/\bCollectionHeader\b/.test(source)) return 'Collection';
  if (/\bDataTable\b/.test(source)) return 'Collection / Report';
  if (/\[[^/]+\]/.test(route)) return 'Record / Detail';
  if (/settings\//.test(route) || /configuration/.test(route) || route === 'pricing') return 'Configuration';
  if (/insights|reports|economics/.test(route)) return 'Insights / Report';
  if (/studio\/website|builder/.test(route)) return 'Builder / Editor';
  return 'Unclassified';
}

const rows = walk(APP_ROOT)
  .map((path) => {
    const source = readFileSync(path, 'utf8');
    const route = routeFrom(path);
    const flags = Object.fromEntries(patterns.map(([name, expression]) => [name, expression.test(source)]));
    return {
      route,
      scope: scope(route),
      archetype: archetype(route, source),
      file: relative(WEB_ROOT, path).replaceAll('\\', '/'),
      ...flags,
      rawH1: (source.match(/<h1\b/g) ?? []).length,
      genericSubtitleSignal: /description=|text-muted[^>]*>[^<{]*(Manage|View|Configure|Review|This page|Use this)/i.test(source),
    };
  })
  .sort((a, b) => a.route.localeCompare(b.route));

const counts = {
  routes: rows.length,
  workspaceHomes: rows.filter((row) => row.WorkspaceHome).length,
  pageHeaders: rows.filter((row) => row.PageHeader).length,
  collectionHeaders: rows.filter((row) => row.CollectionHeader).length,
  collectionViews: rows.filter((row) => row.CollectionView).length,
  dataTables: rows.filter((row) => row.DataTable).length,
  widgetGrids: rows.filter((row) => row.WidgetGrid).length,
  unclassified: rows.filter((row) => row.archetype === 'Unclassified').length,
};

const yes = (value) => value ? '✓' : '—';

const markdown = [
  '# Generated UI surface census',
  '',
  '> Generated by `pnpm audit:ui`. Do not hand-edit; rerun after migrations.',
  '',
  '## Summary',
  '',
  `- Organization routes scanned: **${counts.routes}**`,
  `- WorkspaceHome consumers: **${counts.workspaceHomes}**`,
  `- PageHeader consumers: **${counts.pageHeaders}**`,
  `- CollectionHeader consumers: **${counts.collectionHeaders}**`,
  `- CollectionView consumers: **${counts.collectionViews}**`,
  `- DataTable consumers: **${counts.dataTables}**`,
  `- WidgetGrid consumers: **${counts.widgetGrids}**`,
  `- Unclassified compositions: **${counts.unclassified}**`,
  '',
  '## Surfaces',
  '',
  '| Route | Scope | Inferred archetype | Workspace Home | Page Header | Collection Header | Collection View | ViewNav | DataTable | Widgets | Empty |',
  '|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|',
  ...rows.map((row) =>
    `| \`${row.route || '/'}\` | ${row.scope} | ${row.archetype} | ${yes(row.WorkspaceHome)} | ${yes(row.PageHeader)} | ${yes(row.CollectionHeader)} | ${yes(row.CollectionView)} | ${yes(row.ViewNav)} | ${yes(row.DataTable)} | ${yes(row.WidgetGrid)} | ${yes(row.EmptyState)} |`
  ),
  '',
  '## Signals requiring review',
  '',
  ...rows
    .filter((row) => row.rawH1 > 0 || row.genericSubtitleSignal || row.archetype === 'Unclassified')
    .map((row) => `- \`${row.route || '/'}\` — ${[
      row.rawH1 > 0 ? `${row.rawH1} raw <h1> element(s)` : null,
      row.genericSubtitleSignal ? 'possible generic subtitle/purpose copy' : null,
      row.archetype === 'Unclassified' ? 'composition not recognized by the current audit' : null,
    ].filter(Boolean).join('; ')}`),
  '',
].join('\n');

if (process.argv.includes('--write')) {
  writeFileSync(OUTPUT, markdown);
  process.stdout.write(`Wrote ${OUTPUT}\n`);
} else {
  process.stdout.write(markdown);
}
