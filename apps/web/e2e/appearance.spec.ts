import { test, expect } from '@playwright/test';
import './appearance-env';
import { foundBusiness } from '../tests/support/founding';
import { createWebsite, listSiteTemplates } from '../lib/domain/public-site/public-site';
import { createForm, saveFormDraft, publishFormRevision, formEditorState } from '../lib/domain/forms/forms';
import { setBrand } from '../lib/domain/branding/brand';
import { brandPalette } from '../lib/domain/branding/palette';
import type { Db } from '../lib/db/types';
import { randomUUID } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { createClient } from '@supabase/supabase-js';
import { chooseOption, selectFieldValue } from './select-field';

const url = process.env.SUPABASE_URL!;
const email = `appearance-browser-${randomUUID()}@example.test`;
const otherEmail = `appearance-empty-${randomUUID()}@example.test`;
const password = `appearance-${randomUUID()}`;
const admin = createClient(url, process.env.SUPABASE_SERVICE_ROLE_KEY!, { auth: { persistSession: false } });
const own = createClient(url, process.env.SUPABASE_ANON_KEY!, { auth: { persistSession: false } });
let id: string, otherId: string, first: string, second: string, publicFormKey: string;
const axe = readFileSync(createRequire(`${process.cwd()}/package.json`).resolve('axe-core/axe.min.js'), 'utf8');
const rgb = (hex: string) => `rgb(${[1, 3, 5].map(offset => parseInt(hex.slice(offset, offset + 2), 16)).join(', ')})`;

test.beforeAll(async () => {
  if (!['127.0.0.1', 'localhost'].includes(new URL(url).hostname)) throw new Error('Appearance browser fixtures are local-only.');
  const created = await admin.auth.admin.createUser({ email, password, email_confirm: true });
  if (created.error) throw created.error; id = created.data.user.id;
  const other = await admin.auth.admin.createUser({ email: otherEmail, password, email_confirm: true });
  if (other.error) throw other.error; otherId = other.data.user.id;
  const signed = await own.auth.signInWithPassword({ email, password }); if (signed.error) throw signed.error;
  first = await foundBusiness({ ownerEmail: email, name: 'Appearance browser first', currency: 'USD' });
  second = await foundBusiness({ ownerEmail: email, name: 'Appearance browser second', currency: 'USD' });
  await setBrand(own as Db, { organizationId: second, accent: '#ffffcc', headingFont: 'sans', bodyFont: 'sans' });
  const templates = await listSiteTemplates(own as Db);
  await createWebsite(own as Db, { organizationId: second, templateKey: templates[0]?.key });
  const form = await createForm(own as Db, { organizationId: second, name: 'Appearance public regression' });
  await saveFormDraft(own as Db, { organizationId: second, revisionId: form.revisionId, definition: {
    title: 'Appearance public regression', submitLabel: 'Send', confirmation: { title: 'Received', message: 'Your response was received.' },
    fields: [{ id: 'name', type: 'short_text', label: 'Your name', required: true }],
  } });
  await publishFormRevision(own as Db, { organizationId: second, revisionId: form.revisionId });
  publicFormKey = (await formEditorState(own as Db, second, form.formId))!.form.publicKey;
});
test.afterAll(async () => { for (const account of [id, otherId]) if (account) await admin.auth.admin.deleteUser(account); });

test('draft, durable save, opposite-system theme, account scope, public regression and reset', async ({ page }, info) => {
  await page.emulateMedia({ colorScheme: 'dark', reducedMotion: 'reduce' });
  await own.from('account_appearance_preferences').delete().eq('user_id', id);
  await page.goto('/login');
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Log in', exact: true }).click();
  await expect(page).toHaveURL(/\/organizations\//);
  await page.goto(`/settings/account/appearance?org=${first}`);
  await expect(page.getByRole('heading', { name: 'Appearance', exact: true })).toBeVisible();
  // Preset radios are visually hidden inside their cards; choose one the way a person does (the card),
  // then assert the radio itself is checked, so the accessible control is still what is verified.
  const choose = async (name: string) => {
    const radio = page.getByRole('radio', { name, exact: true });
    await radio.locator('xpath=ancestor::label[1]').click();
    await expect(radio).toBeChecked();
  };
  const shell = page.locator('[data-account-appearance]');
  await expect(shell).not.toHaveAttribute('data-visual-preset');
  await chooseOption(page.getByLabel('Theme', { exact: true }), 'light');
  await choose('Expressive');
  await chooseOption(page.getByLabel('Density', { exact: true }), 'compact');
  await chooseOption(page.getByLabel('Shape', { exact: true }), 'soft');
  await expect(shell).not.toHaveAttribute('data-appearance');
  expect((await own.from('account_appearance_preferences').select()).data).toEqual([]);
  await expect(page.getByTestId('appearance-preview')).toHaveAttribute('data-appearance', 'light');
  await page.getByRole('button', { name: 'Discard changes' }).click();
  await expect(page.getByRole('button', { name: 'Save appearance' })).toBeDisabled();
  await chooseOption(page.getByLabel('Theme', { exact: true }), 'light');
  await choose('Layered');
  await chooseOption(page.getByLabel('Density', { exact: true }), 'comfortable');
  await chooseOption(page.getByLabel('Shape', { exact: true }), 'square');
  await chooseOption(page.getByLabel('Motion', { exact: true }), 'reduced');
  await page.evaluate(() => { (window as unknown as { appearanceContinuity: string }).appearanceContinuity = 'same-document'; });
  await page.getByRole('button', { name: 'Save appearance' }).click();
  await expect(shell).toHaveAttribute('data-appearance', 'light');
  await expect(shell).toHaveAttribute('data-visual-preset', 'layered');
  expect(await page.evaluate(() => (window as unknown as { appearanceContinuity: string }).appearanceContinuity)).toBe('same-document');
  await expect.poll(() => shell.evaluate(element => getComputedStyle(element).backgroundColor)).toBe('rgb(255, 255, 255)');
  const preview = page.getByTestId('appearance-preview');
  const elevation = (locator: typeof preview) => locator.evaluate(el => getComputedStyle(el).getPropertyValue('--visual-elevation').trim());
  const platformElevation = await page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--visual-elevation').trim());
  await choose('Platform default');
  await expect(preview).toHaveAttribute('data-visual-system', '');
  expect(await elevation(shell)).not.toBe(platformElevation);
  expect(await elevation(preview)).toBe(platformElevation);
  const layered = page.getByRole('radio', { name: 'Layered', exact: true });
  await choose('Layered');
  await expect(preview).toHaveAttribute('data-visual-preset', 'layered');
  expect(await elevation(preview)).toBe(await elevation(shell));
  await layered.focus();
  await page.keyboard.press('ArrowRight');
  const expressive = page.getByRole('radio', { name: 'Expressive', exact: true });
  await expect(expressive).toBeChecked();
  await expect(expressive).toBeFocused();
  await expect(preview).toHaveAttribute('data-visual-preset', 'expressive');
  expect(await expressive.evaluate(el => getComputedStyle(el.closest('label')!).boxShadow)).not.toBe('none');
  await page.keyboard.press('ArrowLeft');
  await expect(layered).toBeChecked();
  await expect(page.getByRole('button', { name: 'Save appearance' })).toBeDisabled();
  const rows = async (locator: ReturnType<typeof page.locator>) => Object.values((await locator.evaluateAll(els => els.map(el => Math.round(el.getBoundingClientRect().top))))
    .reduce<Record<number, number>>((count, top) => ({ ...count, [top]: (count[top] ?? 0) + 1 }), {}));
  const tiles = page.locator('[data-slot=preset-choice]');
  await expect(tiles).toHaveCount(4);
  expect(await tiles.evaluateAll(els => els.every(el => el.getBoundingClientRect().height >= 44))).toBe(true);
  const tileRows = await rows(tiles);
  const settingRows = await rows(page.locator('#appearance-theme, #appearance-density, #appearance-shape, #appearance-motion, #appearance-background'));
  if (info.project.name === 'desktop') { expect(tileRows).toEqual([4]); expect(settingRows).toEqual([5]); }
  if (info.project.name === 'phone') { expect(tileRows).toEqual([2, 2]); expect(settingRows).toEqual([1, 1, 1, 1, 1]); }
  expect(new Set(tileRows).size).toBe(1);
  if (info.project.name === 'phone') {
    const menuTrigger = page.getByRole('button', { name: 'Menu', exact: true });
    await menuTrigger.click();
    const sheet = page.getByRole('dialog', { name: 'Sidebar', exact: true });
    await expect(sheet).toBeVisible();
    expect(await sheet.evaluate(el => el.closest('[data-account-appearance]')?.getAttribute('data-appearance'))).toBe('light');
    await page.keyboard.press('Escape');
    await expect(menuTrigger).toBeFocused();
  }
  expect(await page.getByLabel('Example input').evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgba(0, 0, 0, 0)');
  await page.getByRole('button', { name: 'Open preview filter' }).click();
  const feedback = page.getByLabel('Lifecycle', { exact: true });
  await expect(feedback).toBeVisible();
  expect(await feedback.evaluate(el => el.closest('[data-appearance]')?.getAttribute('data-appearance'))).toBe('light');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button', { name: 'Open preview filter' })).toBeFocused();
  await page.addScriptTag({ content: axe });
  const violations = await page.evaluate(async () => (window as unknown as { axe: { run: () => Promise<{ violations: { id: string; nodes: { html: string; failureSummary: string }[] }[] }> } }).axe.run());
  expect(violations.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.failureSummary) }))).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath('appearance-light.png'), fullPage: true });
  await page.getByRole('heading', { name: 'Appearance', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: info.outputPath('appearance-controls-light.png'), fullPage: true });
  await page.reload();
  await expect(shell).toHaveAttribute('data-appearance', 'light');
  const serverHTML = await (await page.request.get(`/settings/account/appearance?org=${first}`)).text();
  expect(serverHTML).toMatch(/<div[^>]*data-account-appearance[^>]*data-appearance="light"/);
  await expect(selectFieldValue(page.getByLabel('Density', { exact: true }))).toHaveValue('comfortable');
  await page.goto(`/organizations/${second}/settings/general`);
  await expect(shell).toHaveAttribute('data-appearance', 'light');
  await expect(shell).toHaveAttribute('data-visual-preset', 'layered');
  // Settings groups are shared cards, so the chosen shape reaches them without a page-local override.
  expect(await page.locator('main [data-slot="card"]').first().evaluate(el => getComputedStyle(el).borderTopLeftRadius)).toBe('4px');
  const palette = brandPalette({ accent: '#ffffcc', headingFont: 'sans', bodyFont: 'sans' });
  expect(await shell.evaluate(el => getComputedStyle(el).getPropertyValue('--accent-text').trim())).toBe(`light-dark(${palette.accentTextLight},${palette.accentTextDark})`);
  await page.goto(`/organizations/${second}/studio/website`);
  const canvas = page.locator('[data-public-design]').first();
  await expect(canvas).toBeVisible();
  expect(await page.locator('button.text-accent-text').first().evaluate(el => getComputedStyle(el).color)).toBe(rgb(palette.accentTextLight));
  await expect.poll(() => canvas.evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgb(10, 10, 10)');
  expect(await canvas.evaluate(el => parseFloat(getComputedStyle(el).getPropertyValue('--visual-radius')))).toBe(.625);
  await page.screenshot({ path: info.outputPath('studio-independent-canvas.png'), fullPage: true });
  await page.goto('/settings/account/appearance?org=00000000-0000-0000-0000-000000000000');
  await expect(page.getByRole('heading', { name: 'Appearance', exact: true })).toBeVisible();
  expect(await page.locator('a[href*="00000000-0000-0000-0000-000000000000"]').count()).toBe(0);
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await chooseOption(page.getByLabel('Motion', { exact: true }), 'system');
  await expect(shell).toHaveAttribute('data-motion', 'reduced');
  const previewInput = page.getByLabel('Example input');
  await expect.poll(() => previewInput.evaluate(el => parseFloat(getComputedStyle(el).transitionDuration))).toBeGreaterThan(.01);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await expect.poll(() => previewInput.evaluate(el => parseFloat(getComputedStyle(el).transitionDuration))).toBeLessThan(.01);
  await page.emulateMedia({ colorScheme: 'light' });
  await chooseOption(page.getByLabel('Theme', { exact: true }), 'dark');
  await page.getByRole('button', { name: 'Save appearance' }).click();
  await expect(shell).toHaveAttribute('data-appearance', 'dark');
  await expect.poll(() => shell.evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgb(10, 10, 10)');
  expect(await page.getByRole('button', { name: 'Reset to defaults' }).evaluate(el => getComputedStyle(el).color)).toBe(rgb(palette.accentTextDark));
  expect(await page.getByLabel('Example input').evaluate(el => getComputedStyle(el).backgroundColor)).not.toBe('rgba(0, 0, 0, 0)');
  await page.screenshot({ path: info.outputPath('appearance-dark.png'), fullPage: true });
  await page.getByRole('heading', { name: 'Appearance', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: info.outputPath('appearance-controls-dark.png'), fullPage: true });
  const fresh = await page.context().browser()!.newContext({ baseURL: info.project.use.baseURL });
  try {
    const otherPage = await fresh.newPage();
    await otherPage.goto('/login');
    await otherPage.getByLabel('Email', { exact: true }).fill(otherEmail);
    await otherPage.getByLabel('Password', { exact: true }).fill(password);
    await otherPage.getByRole('button', { name: 'Log in', exact: true }).click();
    await expect(otherPage).toHaveURL(/\/organizations$/);
    await expect(otherPage.locator('[data-account-appearance]')).not.toHaveAttribute('data-appearance');
    await otherPage.goto('/settings/account/appearance');
    await expect(otherPage.getByRole('heading', { name: 'Appearance', exact: true })).toBeVisible();
    await expect(selectFieldValue(otherPage.getByLabel('Theme', { exact: true }))).toHaveValue('system');
    await expect(otherPage.getByRole('link', { name: 'Appearance', exact: true })).toBeVisible();
    await expect(otherPage.locator('[data-account-appearance]')).not.toHaveAttribute('data-visual-preset');
  } finally { await fresh.close(); }
  const publicResponse = await page.goto('/portal/unavailable');
  expect(publicResponse?.status()).toBe(200);
  await expect(page.locator('[data-account-appearance]')).toHaveCount(0);
  expect(await page.locator('body').evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgb(255, 255, 255)');
  await page.screenshot({ path: info.outputPath('public-portal-unaffected.png'), fullPage: true });
  expect((await page.goto(`/f/${publicFormKey}`))?.status()).toBe(200);
  await expect(page.getByLabel('Your name')).toBeVisible();
  await expect(page.locator('[data-account-appearance], [data-visual-preset]')).toHaveCount(0);
  expect(await page.locator('body').evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgb(255, 255, 255)');
  await page.screenshot({ path: info.outputPath('public-form-unaffected.png'), fullPage: true });
  await page.goto('/settings/account/appearance');
  await expect(shell).toHaveAttribute('data-appearance', 'dark');
  await page.getByRole('button', { name: 'Reset to defaults' }).click();
  await expect(shell).not.toHaveAttribute('data-appearance');
  await expect(shell).not.toHaveAttribute('data-visual-preset');
  expect((await own.from('account_appearance_preferences').select()).data).toEqual([]);
});
