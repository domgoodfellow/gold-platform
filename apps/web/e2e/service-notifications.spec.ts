import { randomUUID } from 'node:crypto';
import path from 'node:path';
import { createClient } from '@supabase/supabase-js';
import { Client } from 'pg';
import { config } from 'dotenv';
import { expect, test } from '@playwright/test';
import type { Database } from '../lib/db/types';
import { provisionOrganization } from '../lib/domain/platform/provision';
import { createCustomer } from '../lib/domain/customers/customers';
import { setModuleEnabled } from '../lib/domain/tenancy/modules';
import { createPortalInvite, exchangePortalLink } from '../lib/domain/portal/portal';
import { createServiceEngagement, attachEngagementDeliverable } from '../lib/domain/customers/service-engagements';
import { portalFromTemplate } from '../lib/domain/portal/composition';
import { savePortalDraft, submitPortalDraft, publishPortalDraft, portalEditorState } from '../lib/domain/portal/definitions';
import { saveServiceDisclosure, releaseServiceDisclosure } from '../lib/domain/customers/service-disclosures';
import { listServiceReviews } from '../lib/domain/customers/service-reviews';
import { createEmailIdentity } from '../lib/domain/email/identities';
import { notificationHistory } from '../lib/domain/customers/service-notifications';
import { createWebsite, siteEditorState, submitSiteRevision, publishSiteRevision } from '../lib/domain/public-site/public-site';
import { chooseOption } from './select-field';

test.use({ storageState: { cookies: [], origins: [] }, hasTouch: true, trace: 'off' });
test('verified recipient consent, notification delivery, retry and responsive operator controls', async ({ page, browser }, testInfo) => {
  test.setTimeout(300_000);
  config({ path: path.join(__dirname, '../../..', '.env.test') });
  const url = process.env.SUPABASE_URL!; const connection = process.env.SUPABASE_DB_URL!;
  if (![url, connection].every(value => ['localhost', '127.0.0.1'].includes(new URL(value).hostname))) throw new Error('Disposable loopback fixtures only');
  const admin = createClient<Database>(url, process.env.SUPABASE_SERVICE_ROLE_KEY!, { auth: { persistSession: false } });
  const client = () => createClient<Database>(url, process.env.SUPABASE_ANON_KEY!, { auth: { persistSession: false } });
  const email = `batch-e-${randomUUID()}@example.test`; const password = randomUUID();
  const made = await admin.auth.admin.createUser({ email, password, email_confirm: true }); if (made.error) throw made.error;
  const operator = client(); const login = await operator.auth.signInWithPassword({ email, password }); if (login.error) throw login.error;
  const pg = new Client(connection); await pg.connect();
  const customerContext = await browser.newContext({ ignoreHTTPSErrors: true, hasTouch: true });
  const otherContext = await browser.newContext({ ignoreHTTPSErrors: true });
  const customerPage = await customerContext.newPage(); const otherPage = await otherContext.newPage();
  try {
    await pg.query('insert into platform_staff(user_id,name) values($1,$2)', [made.data.user.id, 'Local Batch D fixture']);
    const org = await provisionOrganization(operator, { ownerEmail: email, name: 'GildOps review fixture', currency: 'CAD', displayName: 'Delivery operator' });
    const tenant = await provisionOrganization(operator, { ownerEmail: email, name: 'Independent website tenant', currency: 'CAD', displayName: 'Independent tenant owner' });
    const customer = await createCustomer(operator, { organizationId: org, name: 'Acme Plumbing' });
    const otherCustomer = await createCustomer(operator, { organizationId: org, name: 'Second customer' });
    const relationship = await operator.rpc('link_existing_client_tenant', { p_organization_id: org, p_customer_id: customer, p_tenant_id: tenant, p_authority_basis: 'Local verified delivery fixture' }); if (relationship.error) throw relationship.error;
    const engagement = await createServiceEngagement(operator, { organizationId: org, customerId: customer, name: 'Website implementation', serviceKind: 'website', relationshipId: relationship.data });
    await createWebsite(operator, { organizationId: tenant });
    const site = (await siteEditorState(operator, tenant))!;
    await submitSiteRevision(operator, tenant, site.working!.id); await publishSiteRevision(operator, tenant, site.working!.id);
    const deliverable = await attachEngagementDeliverable(operator, org, engagement, 'website', site.siteId);
    await setModuleEnabled(operator, { organizationId: org, key: 'portal', enabled: true });
    await pg.query("insert into organization_commercial_terms(organization_id,product_key,period_start,period_end,quantity,price_minor,currency,recorded_by,note) values($1,'module:portal','2020-01-01','9999-12-31',1,0,'CAD',$2,'Local review browser fixture')", [org, made.data.user.id]);
    const sellerHost = `review-${randomUUID()}.example.test`; const websiteHost = `website-${randomUUID()}.example.test`;
    for (const [target, host, surface] of [[org, sellerHost, 'portal'], [tenant, websiteHost, 'website']] as const) {
      const domain = await operator.rpc('begin_custom_domain_connection', { p_organization_id: target, p_hostname: host, p_surface: surface }); if (domain.error) throw domain.error;
      await pg.query('begin'); await pg.query('set local role provider_operator');
      await pg.query("select record_custom_domain_registration($1,$2,'satisfied','[]'::jsonb,null,null)", [target, domain.data]);
      await pg.query("select set_custom_domain_verification($1,$2,'verified','satisfied','issued',null,null,null)", [target, domain.data]); await pg.query('commit');
    }
    await savePortalDraft(operator, org, 0, portalFromTemplate('managed-services'));
    await submitPortalDraft(operator, org, (await portalEditorState(operator, org)).definition!.draft_version);
    await publishPortalDraft(operator, org, (await portalEditorState(operator, org)).definition!.draft_version);
    await saveServiceDisclosure(operator, org, customer, engagement, 0, { title: 'Website ready for review', serviceKind: 'website', summary: 'Review the website and the approved delivery summary.', status: 'Ready for review', deliverables: [{ deliverableId: deliverable, title: 'Acme website', summary: 'Booking form and service pages are prepared.', status: 'Ready for review', shareLink: true }] });
    await releaseServiceDisclosure(operator, org, customer, engagement, 1, 'publish');
    const token = await createPortalInvite(operator, { customerId: customer }); const otherToken = await createPortalInvite(operator, { customerId: otherCustomer });
    const portalDb = client(); const otherDb = client(); await exchangePortalLink(portalDb, { token }); await exchangePortalLink(otherDb, { token: otherToken });
    await pg.query('delete from platform_staff where user_id=$1', [made.data.user.id]);
    const tls = new URL(process.env.E2E_PORTAL_TLS_URL ?? 'https://localhost:3148');
    const origin = `https://${sellerHost}:${tls.port}`;
    const customerPath = `/organizations/${org}/crm/contacts/${customer}`;
    const openEngagement = async () => {
      await page.goto(customerPath); await page.getByRole('tab', { name: 'Commercial proposal', exact: true }).click();
      await page.getByRole('button', { name: 'View engagement', exact: true }).click();
    };
    await page.goto('/login'); await page.getByLabel('Email', { exact: true }).fill(email); await page.getByLabel('Password', { exact: true }).fill(password);
    await page.getByRole('button', { name: 'Log in', exact: true }).click(); await page.waitForURL(value => value.pathname !== '/login');
    await openEngagement(); const drawer = page.getByRole('dialog', { name: 'Website implementation', exact: true });
    const requestReview = async () => {
      await chooseOption(drawer.getByLabel('Review target'), deliverable);
      await drawer.getByRole('button', { name: 'Request customer review', exact: true }).click();
      await expect(drawer.getByText('Review pending', { exact: true })).toBeVisible();
    };
    const domainName = `notify-${randomUUID()}.example.test`;
    const named = await operator.rpc('record_organization_email_domain', { p_organization_id: org, p_domain: domainName }); if (named.error) throw named.error;
    const identity = await createEmailIdentity(operator, { organizationId: org, address: `service@${domainName}`, sendingDomainResourceId: named.data });
    await pg.query("select record_email_domain_provisioning($1,$2,'active')", [org, named.data]);
    await operator.rpc('set_customer_notification_sender', { p_organization_id: org, p_customer_id: customer, p_email_identity_id: identity.id });
    await openEngagement();
    await expect(drawer.getByLabel('Notify customer by email')).toBeDisabled();
    await requestReview();
    await expect(drawer.getByText('Notification: Not requested', { exact: true })).toBeVisible();
    await customerPage.goto(`${origin}/portal/${token}`);
    await customerPage.getByText('Email notifications', { exact: true }).click();
    const checks = customerPage.locator('input[name="purposes"]');
    for (let i = 0; i < 3; i++) await expect(checks.nth(i)).not.toBeChecked();
    await customerPage.getByLabel('Notification email address').fill(`customer-${randomUUID()}@example.test`);
    await customerPage.getByLabel('Deliverables ready for review', { exact: true }).check();
    await customerPage.getByLabel('Service progress updates', { exact: true }).check();
    await customerPage.getByRole('button', { name: 'Send confirmation code', exact: true }).click();
    await expect(customerPage.getByRole('status').filter({ hasText: 'Confirmation queued' })).toBeVisible();
    await expect(customerPage.getByLabel('Email confirmation code')).toBeFocused();
    const challenge = (await pg.query('select c.id,m.body from app.notification_challenges c join app.notification_jobs j on j.organization_id=c.organization_id and j.challenge_id=c.id join messages m on m.organization_id=j.organization_id and m.id=j.message_id where c.organization_id=$1 and c.customer_id=$2 order by c.created_at desc limit 1', [org, customer])).rows[0];
    await customerPage.getByLabel('Email confirmation code').fill(challenge.body.match(/: ([a-f0-9]{16})/)[1]);
    await customerPage.getByRole('button', { name: 'Verify address and save preferences' }).click();
    await expect(customerPage.getByRole('status').filter({ hasText: 'Email verified' })).toBeFocused();
    await expect(customerPage.getByRole('button', { name: 'Turn off email notifications' })).toBeVisible();
    await releaseServiceDisclosure(operator, org, customer, engagement, 2, 'publish', false);
    await openEngagement();
    await drawer.getByLabel('Notify customer by email').check();
    await requestReview();
    const current = (await listServiceReviews(operator, org, customer, engagement))[0];
    await expect(drawer.getByText('Notification: Queued', { exact: true })).toBeVisible();
    const claim = async () => {
      const job = (await pg.query('select j.id from app.notification_jobs j join service_notification_intents i on i.organization_id=j.organization_id and i.id=j.intent_id where i.review_id=$1', [current.id])).rows[0];
      await pg.query('update app.notification_jobs set next_attempt_at=now() where id=$1', [job.id]);
      return (await pg.query('select claim_customer_notification($1) value', [job.id])).rows[0].value;
    };
    const first = await claim();
    await pg.query("select finish_customer_notification($1,$2,'retry',null)", [first.job_id, first.lease_id]);
    await openEngagement();
    await drawer.getByText(/Delivery history \(/).click();
    await drawer.getByRole('button', { name: 'Retry notification' }).click();
    const second = await claim(); expect(second.message_id).toBe(first.message_id);
    await pg.query("select finish_customer_notification($1,$2,'accepted',$3)", [second.job_id, second.lease_id, `browser-${current.id}`]);
    await openEngagement();
    await expect(drawer.getByText('Notification: Accepted by provider', { exact: true })).toBeVisible();
    await pg.query("select record_email_event($1,'sent',$2,null,'{}',now())", [`browser-${current.id}`, randomUUID()]);
    await pg.query("select record_email_event($1,'delivered',$2,null,'{}',now())", [`browser-${current.id}`, randomUUID()]);
    await openEngagement();
    await expect(drawer.getByText('Notification: Delivered', { exact: true })).toBeVisible();
    for (const [width, height, label] of [[1440, 900, 'desktop'], [768, 900, 'tablet'], [390, 844, 'phone']] as const) {
      await page.setViewportSize({ width, height }); await customerPage.setViewportSize({ width, height });
      await drawer.getByText(/Delivery history \(/).press('Enter');
      await expect(drawer.getByText('View delivery details').first()).toBeVisible();
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
      expect(await customerPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
      await page.screenshot({ path: testInfo.outputPath(`notifications-${label}.png`) });
      await customerPage.screenshot({ path: testInfo.outputPath(`preferences-${label}.png`) });
      if (width === 390) await drawer.getByText(/Delivery history \(/).tap();
      else await drawer.getByText(/Delivery history \(/).press('Enter');
    }
    await releaseServiceDisclosure(operator, org, customer, engagement, 3, 'publish', false);
    await openEngagement(); await drawer.getByLabel('Notify customer by email').check(); await requestReview();
    const obsolete = (await listServiceReviews(operator, org, customer, engagement))[0];
    await expect(drawer.getByText('Notification: Queued', { exact: true })).toBeVisible();
    await releaseServiceDisclosure(operator, org, customer, engagement, 4, 'publish', false);
    const obsoleteJob = (await pg.query('select j.id from app.notification_jobs j join service_notification_intents i on i.organization_id=j.organization_id and i.id=j.intent_id where i.review_id=$1', [obsolete.id])).rows[0];
    expect((await pg.query('select claim_customer_notification($1) value', [obsoleteJob.id])).rows[0].value.held).toBe(true);
    await openEngagement();
    await expect(drawer.getByText(/Notification: Suppressed \/ ineligible.*superseded/)).toBeVisible();
    await otherPage.goto(`${origin}/portal/${otherToken}`);
    await otherPage.getByText('Email notifications', { exact: true }).click();
    await expect(otherPage.getByText('Confirm your email in this session to view or change notification preferences.', { exact: false })).toBeVisible();
    expect((await otherDb.rpc('confirm_notification_recipient', { p_challenge_id: challenge.id, p_code: 'incorrect' })).data).toBe(false);
    await customerPage.getByRole('button', { name: 'Turn off email notifications' }).click();
    await expect(customerPage.getByRole('status').filter({ hasText: 'Email notifications are off' })).toBeFocused();
    await releaseServiceDisclosure(operator, org, customer, engagement, 5, 'publish', true);
    expect((await notificationHistory(operator, org, customer, engagement)).find(n => n.purpose === 'service_update_published')?.state).toBe('suppressed');
  } finally { await customerContext.close(); await otherContext.close(); await pg.end(); }
});
