import { expect, test } from '@playwright/test';
import { createClient } from '@supabase/supabase-js';
import { config as loadEnv } from 'dotenv';
import path from 'node:path';
import { loadDemoContext, OWNER_STORAGE_STATE, COLLEAGUE_STORAGE_STATE } from './helpers';
import { DEMO_PASSWORD } from '../scripts/demo/businesses';
import { provisionOrganization } from '../lib/domain/platform/provision';
import { setModuleEnabled } from '../lib/domain/tenancy/modules';
import { createCustomer } from '../lib/domain/customers/customers';
import { createWorkItemType } from '../lib/domain/work-items/types';
import { createWorkItemStatus } from '../lib/domain/work-items/statuses';
import { createWorkItem } from '../lib/domain/work-items/work-items';
import { addPricedLine, listPricedLines } from '../lib/domain/pricing/prices';
import { getInvoiceForWorkItem, issueInvoice, recordPayment } from '../lib/domain/billing/invoices';
import { todayInZone, shiftDate, zonedTimeToInstant } from '../lib/domain/scheduling/window';

test.describe('Finance operating journey', () => {
  test.use({ storageState: OWNER_STORAGE_STATE });
  test('manages pricing, quotes, issuance, partial and final payments with responsive dashboard', async ({ page }, testInfo) => {
    test.setTimeout(240000); page.setDefaultTimeout(15000);
    const browserErrors: string[] = [];
    page.on('pageerror', error => browserErrors.push(error.message));
    loadEnv({ path: path.join(__dirname,'..','..','..','.env.test') });
    const url = process.env.SUPABASE_URL!;
    if (!['localhost','127.0.0.1'].includes(new URL(url).hostname)) throw new Error('Local Finance fixtures only.');
    const options = { auth: { persistSession: false, autoRefreshToken: false } };
    const staff = createClient(url,process.env.SUPABASE_ANON_KEY!,options), owner = createClient(url,process.env.SUPABASE_ANON_KEY!,options);
    const ctx = loadDemoContext();
    for (const [db,email] of [[staff,'staff@gold.test'],[owner,ctx.ownerEmail]] as const) { const {error}=await db.auth.signInWithPassword({email,password:DEMO_PASSWORD}); if(error)throw error; }
    const organizationId = await provisionOrganization(staff,{ownerEmail:ctx.ownerEmail,name:`Finance acceptance ${Date.now()}`,displayName:'Finance owner',currency:'CAD',timezone:'America/Toronto'});
    const base = `/organizations/${organizationId}`, finance = `${base}/finance`;
    await setModuleEnabled(owner,{organizationId,key:'billing',enabled:true});
    await page.setViewportSize({width:1440,height:1000});
    await page.goto(finance);
    await expect(page.getByRole('region',{name:'Open invoices',exact:true}).getByText('No invoices issued yet.')).toBeVisible();
    await page.screenshot({path:testInfo.outputPath('finance-empty-desktop.png'),fullPage:true,caret:'initial'});
    await page.getByRole('navigation',{name:'Finance destinations'}).getByRole('link',{name:'Services & Pricing'}).click();
    await page.getByRole('button',{name:'Add price item',exact:true}).click();
    let drawer = page.getByRole('dialog',{name:'Add price item',exact:true});
    await drawer.getByRole('textbox',{name:'Name',exact:true}).fill('Service visit');
    await drawer.getByRole('textbox',{name:'Unit',exact:true}).fill('visit');
    await drawer.getByLabel('Amount in CAD',{exact:true}).fill('2400');
    await drawer.getByRole('button',{name:'Add',exact:true}).click();
    await expect(drawer.getByRole('status')).toHaveText('Saved.');
    await drawer.getByRole('button',{name:'Close',exact:true}).click();
    const price = (await owner.from('price_book_items').select('id').eq('organization_id',organizationId).single()).data!;
    const typeId = await createWorkItemType(owner,{organizationId,name:'Service',schedulable:false});
    const statusId = await createWorkItemStatus(owner,{organizationId,typeId,name:'Open',position:0});
    const customerId = await createCustomer(owner,{organizationId,name:'North Shore Plumbing'});
    const workId = await createWorkItem(owner,{organizationId,statusId,title:'Service quote acceptance',customerId});
    await page.getByRole('button',{name:'Edit Service visit',exact:true}).filter({visible:true}).click();
    drawer = page.getByRole('dialog',{name:'Edit price item',exact:true});
    await drawer.getByLabel('Name of Service visit').fill('Service inspection');
    await drawer.getByLabel('Amount for Service visit').fill('2500');
    await drawer.getByRole('button',{name:'Save',exact:true}).click();
    await expect(drawer.getByRole('status')).toHaveText('Saved.');
    await drawer.getByRole('button',{name:'Close',exact:true}).click();
    await page.screenshot({path:testInfo.outputPath('finance-pricing-desktop.png'),fullPage:true,caret:'initial'});
    await page.getByRole('link',{name:'Manage payment features',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Features',exact:true})).toBeVisible();
    await page.goto(finance);
    await page.getByRole('button',{name:'New quote',exact:true}).click();
    drawer = page.getByRole('dialog',{name:'New quote',exact:true});
    await drawer.getByLabel('Find a record').fill('Service quote acceptance');
    await expect(drawer.getByRole('option',{name:'Service quote acceptance',exact:true})).toHaveCount(1);
    await drawer.getByLabel('Work item',{exact:true}).selectOption(workId);
    await drawer.getByLabel('Price book item').selectOption(price.id);
    await drawer.getByRole('button',{name:'Add to quote',exact:true}).click();
    await expect(drawer.getByRole('status')).toContainText('Priced line added');
    await drawer.getByRole('link',{name:'View Quotes',exact:true}).click();
    await expect(page.getByRole('link',{name:'Service quote acceptance',exact:true}).filter({visible:true})).toBeVisible();
    await page.screenshot({path:testInfo.outputPath('finance-quotes-desktop.png'),fullPage:true,caret:'initial'});
    await page.goto(finance);
    await page.getByRole('button',{name:'New invoice',exact:true}).click();
    drawer = page.getByRole('dialog',{name:'New invoice',exact:true});
    await drawer.getByLabel('Find a record').fill('North Shore');
    await expect(drawer.getByRole('option',{name:/Service quote acceptance/})).toHaveCount(1);
    await drawer.getByLabel('Work item',{exact:true}).selectOption(workId);
    const today = todayInZone('America/Toronto');
    await drawer.getByLabel(/Invoice date/).fill(today);
    await drawer.getByLabel(/Due date/).fill(shiftDate(today,7));
    await page.screenshot({path:testInfo.outputPath('finance-new-invoice-desktop.png'),fullPage:true,caret:'initial'});
    await drawer.getByRole('button',{name:'Confirm issue invoice',exact:true}).click();
    await expect(drawer.getByRole('status')).toContainText('Invoice issued.');
    await drawer.getByRole('button',{name:'Close',exact:true}).click();
    for (const amount of ['1000','1500']) {
      await page.getByRole('button',{name:'Record payment',exact:true}).first().click();
      drawer = page.getByRole('dialog',{name:'Record payment',exact:true});
      await drawer.getByLabel('Find a record').fill('North Shore');
      await expect(drawer.getByRole('option',{name:/North Shore/})).toHaveCount(1);
      await drawer.getByLabel('Invoice',{exact:true}).selectOption(workId);
      if (amount === '1000') {
        await drawer.getByLabel('Amount (CAD)',{exact:true}).fill('0');
        await drawer.getByRole('button',{name:'Save payment',exact:true}).click();
        await expect(drawer.getByRole('alert')).toContainText('payment');
        await expect(drawer.getByLabel('Amount (CAD)',{exact:true})).toHaveValue('0');
      }
      await drawer.getByLabel('Amount (CAD)',{exact:true}).fill(amount);
      await page.screenshot({path:testInfo.outputPath(`finance-record-payment-${amount}.png`),fullPage:true,caret:'initial'});
      await drawer.getByRole('button',{name:'Save payment',exact:true}).click();
      await expect(drawer.getByRole('status')).toContainText('Payment recorded.');
      await drawer.getByRole('button',{name:'Close',exact:true}).click();
      const invoice = await getInvoiceForWorkItem(owner,{organizationId,workItemId:workId});
      expect(invoice!.payments.length).toBe(amount==='1000'?1:2);
    }
    const names=['Vertex HVAC','Maple Dental','Aster Electric','Lumière Studio','Riverside Property','Cedar Tree Properties'];
    for (let i=0;i<names.length;i++) {
      const customerId = await createCustomer(owner,{organizationId,name:names[i]});
      const id = await createWorkItem(owner,{organizationId,statusId,title:`Inspection · ${names[i]}`,customerId});
      await addPricedLine(owner,{workItemId:id,priceBookItemId:price.id,quantity:i+1});
      if(i===5)continue;
      const invoiceId=await issueInvoice(owner,{workItemId:id,issuedAt:zonedTimeToInstant(shiftDate(today,-10),'00:00','America/Toronto'),dueAt:zonedTimeToInstant(shiftDate(today,i<3?-i-1:0),'12:00','America/Toronto')});
      if(i<3)await recordPayment(owner,{invoiceId,amountMinor:50000+i*10000});
    }
    await page.goto(finance);
    await expect(page.getByRole('tab',{name:/Overdue invoices \(3\)/})).toBeVisible();
    await page.screenshot({path:testInfo.outputPath('finance-populated-desktop.png'),fullPage:true,caret:'initial'});
    await page.getByRole('region',{name:'Collections & financial performance',exact:true}).scrollIntoViewIfNeeded();
    await page.screenshot({path:testInfo.outputPath('finance-populated-desktop-lower.png'),fullPage:true,caret:'initial'});
    await page.getByRole('region',{name:'Today / due items',exact:true}).getByRole('link',{name:/View all/}).click();
    await expect(page.getByLabel('Due on',{exact:true})).toHaveValue(today);
    await expect(page.getByRole('navigation',{name:'Pagination'})).toContainText('2 records');
    await page.goto(finance);
    await page.getByRole('tab',{name:/Overdue invoices \(3\)/}).focus();
    await page.keyboard.press('End');
    await expect(page.getByRole('tab',{name:/Payment setup/})).toHaveAttribute('aria-selected','true');
    await page.keyboard.press('Home');
    await expect(page.getByRole('tab',{name:/Overdue invoices \(3\)/})).toHaveAttribute('aria-selected','true');
    await page.getByRole('tab',{name:/Quoted, not invoiced/}).scrollIntoViewIfNeeded();
    await page.getByRole('tab',{name:/Quoted, not invoiced/}).click();
    await expect(page.getByRole('tabpanel').getByRole('link',{name:'Cedar Tree Properties',exact:true}).filter({visible:true})).toBeVisible();
    for(const kind of ['invoices','payments']) { await page.goto(`${finance}/${kind}`); await page.screenshot({path:testInfo.outputPath(`finance-${kind}-desktop.png`),fullPage:true,caret:'initial'}); }
    await page.goto(`${finance}/reports`);await expect(page.getByRole('heading',{name:'Financial performance',exact:true})).toBeVisible();await expect(page.getByRole('columnheader',{name:'Margin on recorded costs',exact:true})).toBeVisible();
    await page.goto(`${finance}/invoices?status=overdue`);await expect(page.getByLabel('Status',{exact:true})).toHaveValue('overdue');await page.reload();await expect(page.getByLabel('Status',{exact:true})).toHaveValue('overdue');
    await page.getByRole('link',{name:'#2',exact:true}).filter({visible:true}).click();await expect(page.getByRole('tab',{name:'Financials',exact:true})).toHaveAttribute('data-state','active');
    await page.goto(finance);await page.getByLabel('Reporting month',{exact:true}).fill('2025-12');await expect(page).toHaveURL(/month=2025-12/);await expect(page.getByLabel('Reporting month',{exact:true})).toHaveValue('2025-12');await expect(page.getByRole('link',{name:/Payments received No payments recorded/})).toBeVisible();
    await page.getByRole('searchbox',{name:'Search Finance',exact:true}).fill('Vertex');await page.getByRole('searchbox',{name:'Search Finance',exact:true}).press('Enter');await expect(page).toHaveURL(/finance\/search\?q=Vertex/);await expect(page.getByRole('link',{name:'Vertex HVAC',exact:true}).filter({visible:true}).first()).toBeVisible();
    for(const width of [768,390]) { await page.setViewportSize({width,height:1000});await page.goto(finance);await expect(page.getByRole('heading',{name:'Finance',exact:true})).toBeVisible();expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);await page.screenshot({path:testInfo.outputPath(`finance-populated-${width}.png`),fullPage:true,caret:'initial'});await page.getByRole('region',{name:'Insights',exact:true}).scrollIntoViewIfNeeded();await page.screenshot({path:testInfo.outputPath(`finance-populated-${width}-lower.png`),fullPage:true,caret:'initial'}); }
    await page.getByRole('button',{name:'Record payment',exact:true}).first().scrollIntoViewIfNeeded();
    await page.getByRole('button',{name:'Record payment',exact:true}).first().click();
    drawer = page.getByRole('dialog',{name:'Record payment',exact:true});
    await drawer.getByLabel('Find a record').fill('Vertex');
    await expect(drawer.getByRole('option',{name:/Vertex HVAC/})).toHaveCount(1);
    await drawer.getByLabel('Invoice',{exact:true}).selectOption({label:await drawer.getByRole('option',{name:/Vertex HVAC/}).textContent() ?? ''});
    await expect(drawer.getByLabel('Amount (CAD)',{exact:true})).toBeVisible();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
    await page.screenshot({path:testInfo.outputPath('finance-payment-mobile.png'),fullPage:true,caret:'initial'});
    await drawer.getByRole('button',{name:'Close',exact:true}).click();
    await page.setViewportSize({width:1440,height:1000});
    await page.goto(`/organizations/${organizationId}/settings/pricing`);
    await page.getByText('Change trading currency',{exact:true}).click();
    await page.getByLabel('Currency',{exact:true}).selectOption('USD');
    await page.getByRole('button',{name:'Save currency',exact:true}).click();
    await expect(page.getByRole('status')).toHaveText('Saved.');
    await page.getByRole('button',{name:'Edit Service inspection',exact:true}).filter({visible:true}).click();
    drawer = page.getByRole('dialog',{name:'Edit price item',exact:true});
    await drawer.getByLabel('Amount for Service inspection').fill('3000');
    await drawer.getByRole('button',{name:'Save',exact:true}).click();
    await expect(drawer.getByRole('status')).toHaveText('Saved.');
    await drawer.getByRole('button',{name:'Close',exact:true}).click();
    const lines = await listPricedLines(owner,{organizationId,workItemId:workId});expect(lines[0].unitAmountMinor).toBe(250000);expect(lines[0].currency).toBe('CAD');
    const originalInvoice = await getInvoiceForWorkItem(owner,{organizationId,workItemId:workId});expect(originalInvoice!.lines[0].unitAmountMinor).toBe(250000);expect(originalInvoice!.currency).toBe('CAD');
    for(let i=0;i<21;i++) { const id=await createWorkItem(owner,{organizationId,statusId,title:`Pagination ${i}`,customerId});await addPricedLine(owner,{workItemId:id,priceBookItemId:price.id,quantity:1});await issueInvoice(owner,{workItemId:id}); }
    await page.goto(`${finance}/invoices`);
    await expect(page.getByRole('navigation',{name:'Pagination'})).toContainText('Page 1 · 27 records');
    await page.getByRole('link',{name:'Next',exact:true}).click();
    await expect(page).toHaveURL(/page=2/);
    await expect(page.getByRole('navigation',{name:'Pagination'})).toContainText('Page 2 · 27 records');
    await page.getByRole('link',{name:'Previous',exact:true}).click();
    await expect(page).toHaveURL(/page=1/);
    expect(browserErrors).toEqual([]);
  });
});
