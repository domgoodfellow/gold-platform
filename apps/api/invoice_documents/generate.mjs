import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

/**
 * Bundles apps/web's invoice composition and PDF layout into `document.generated.mjs`, so the
 * writer draws an issued invoice with the one implementation apps/web draws drafts with -- never
 * a copy kept by hand. React and the PDF library stay imports, resolved from apps/api's own
 * dependencies at the same versions apps/web pins.
 *
 *   node invoice_documents/generate.mjs           # write
 *   node invoice_documents/generate.mjs --check   # fail if the committed file is stale
 */

const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const OUT = fileURLToPath(new URL('./document.generated.mjs', import.meta.url));

const result = await build({
  stdin: {
    contents: [
      "export { composeInvoiceDocument, drawWithLogoFallback, isPdf, logoFormat, presentationFrom } from './lib/domain/billing/invoice-document';",
      "export { reactPdfRenderer } from './lib/adapters/documents/react-pdf';",
    ].join('\n'),
    resolveDir: `${ROOT}apps/web`,
    sourcefile: 'invoice-document-entry.ts',
    loader: 'ts',
  },
  absWorkingDir: ROOT,
  tsconfig: `${ROOT}apps/web/tsconfig.json`,
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node20',
  jsx: 'automatic',
  external: ['@react-pdf/renderer', 'react', 'react/jsx-runtime'],
  legalComments: 'none',
  write: false,
});

const banner = '// GENERATED by apps/api/invoice_documents/generate.mjs from apps/web. Do not edit; run it again.\n';
const generated = banner + result.outputFiles[0].text;
const normalised = (text) => text.replace(/\r\n/g, '\n');

if (process.argv.includes('--check')) {
  let committed = '';
  try { committed = readFileSync(OUT, 'utf8'); } catch { /* Missing counts as stale. */ }
  if (normalised(committed) !== normalised(generated)) {
    process.stderr.write('apps/api/invoice_documents/document.generated.mjs is stale. Run: pnpm --filter @gold/integration-library invoice-documents:generate\n');
    process.exit(1);
  }
} else {
  writeFileSync(OUT, generated);
}
