import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { identity, categoryFor, workspaceFor, reads } from './policy.mjs';

const root = new URL('../', import.meta.url);
const pkg = JSON.parse(await readFile(new URL('package.json', root), 'utf8'));
const applications = [];
const imports = [];
function schemaFor(props) {
  const properties = {}, required = [];
  for (const [key, p] of Object.entries(props)) {
    if (p.type === 'MARKDOWN') continue;
    const type = ({ SHORT_TEXT: 'string', LONG_TEXT: 'string', NUMBER: 'number', CHECKBOX: 'boolean', JSON: 'object',
      ARRAY: 'array', STATIC_MULTI_SELECT_DROPDOWN: 'array', MULTI_SELECT_DROPDOWN: 'array', OBJECT: 'object' })[p.type] ?? 'string';
    properties[key] = { type, description: p.displayName ?? key, ...(type === 'string' ? { maxLength: 2000 } : {}) };
    if (p.defaultValue !== undefined) properties[key].default = p.defaultValue;
    if (p.required && p.defaultValue === undefined) required.push(key);
  }
  return { type: 'object', properties, required, additionalProperties: false };
}
for (const [name, version] of Object.entries(pkg.dependencies).filter(([n]) => n.startsWith('@activepieces/piece-')).sort()) {
  const slug = name.slice('@activepieces/piece-'.length);
  const module = await import(name);
  const exported = Object.entries(module).find(([, v]) => typeof v?.metadata === 'function');
  if (!exported) throw new Error(`${name} exports no piece`);
  imports.push(`  ${JSON.stringify(slug)}: async () => (await import(${JSON.stringify(name)}))[${JSON.stringify(exported[0])}],`);
  const m = exported[1].metadata();
  const auths = Array.isArray(m.auth) ? m.auth : [m.auth];
  const oauth = auths.find(a => a?.type === 'OAUTH2' && !a.props);
  const secret = auths.find(a => a?.type === 'SECRET_TEXT');
  const category = categoryFor(slug);
  const actions = Object.entries(m.actions).map(([key, a]) => ({
    key, capability: `piece.${slug.replaceAll('-', '_')}.${key}`, name: a.displayName,
    description: (a.description ?? '').slice(0, 300), classification: a.classification ?? 'UNKNOWN',
    executable: (reads[slug] ?? []).includes(key) && ['READ', 'SEARCH'].includes(a.classification),
    inputs: (reads[slug] ?? []).includes(key) ? schemaFor(a.props) : undefined,
  }));
  applications.push({ key: slug, connector_key: identity(slug), package: name, version, name: m.displayName,
    description: m.description ?? '', icon: m.logoUrl, category, workspace: workspaceFor(category),
    auth: oauth ? { type: 'oauth2', authorize_url: oauth.authUrl, token_url: oauth.tokenUrl, scopes: oauth.scope,
      authorization_method: oauth.authorizationMethod ?? 'BODY' } : secret ? { type: 'api_key', label: secret.displayName,
      description: (secret.description ?? '').slice(0, 4000), verifiable: !!secret.validate || actions.some(a=>a.executable && a.inputs.required.length===0) }
      : { type: 'custom', description: 'This connector requires an application-specific authentication configuration.' },
    actions, triggers: Object.entries(m.triggers).map(([key, t]) => ({ key, name: t.displayName, strategy: t.type })),
  });
}
const catalogue = JSON.stringify({ source: 'activepieces', applications }, null, 2) + '\n';
const loaders = '// Generated by library/generate.mjs. Only pinned package imports; never imports a caller-supplied module.\nexport const loaders = {\n' + imports.join('\n') + '\n};\n';
for (const [name, data] of [['catalogue.json', catalogue], ['loaders.mjs', loaders]]) {
  const file = new URL(name, import.meta.url);
  if (process.argv.includes('--check')) {
    if (await readFile(file, 'utf8') !== data) throw new Error(`${fileURLToPath(file)} is stale; run library:generate`);
  } else await writeFile(file, data);
}
console.log(`${applications.length} imported applications; ${applications.reduce((n, a) => n + a.actions.filter(x => x.executable).length, 0)} approved reads`);
const publicData = JSON.stringify({ applications: applications.map(app => ({ ...app,
  actions: app.actions.filter(a => a.executable), triggers: [], trigger_count: app.triggers.length })) }, null, 2) + '\n';
const webFile = new URL('../../../apps/web/lib/contracts/integrations/library.generated.json', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(webFile, 'utf8') !== publicData) throw new Error('Web library metadata is stale.');
} else {
  const { mkdir } = await import('node:fs/promises');
  await mkdir(new URL('.', webFile), { recursive: true });
  await writeFile(webFile, publicData);
}
