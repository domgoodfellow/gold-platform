-- The customer portal, and the gap D22 left open for it.
--
-- D22, as amended by the booking slice, ends: "The portal will need to bind an outsider to a
-- customer the *business* created, which `created_by` cannot express — that is a real gap and
-- it gets its column when it has a caller, not before." This is that caller.
--
-- **Booking scopes an outsider to rows they made; the portal scopes them to rows about them.**
-- A booking visitor created their own customer row, so `created_by = auth.uid()` identified it
-- exactly. A customer of ten years never created anything — the business did — so there is
-- nothing on those rows carrying their identity. What binds them is a link the business sent.
--
-- **Why a link and not an email sign-in.** Proving control of an address means sending to it,
-- and channels are M6's. A business already has a way to reach its customers; this gives it a
-- URL to put in whatever it already uses. The consequence is stated rather than hidden: anyone
-- holding the link is the customer, which is the same security model as a link to a shared
-- document, and it is the business's to revoke.

-- ---------------------------------------------------------------------------
-- The invitation
-- ---------------------------------------------------------------------------

create table public.customer_portal_invites (
  id              uuid        primary key default gen_random_uuid(),
  organization_id uuid        not null references public.organizations (id) on delete cascade,
  customer_id     uuid        not null,

  -- The secret in the URL. Generated by the database, never by a caller: a client that could
  -- choose it could choose one already issued to somebody else.
  token           text        not null check (length(token) >= 32),

  created_at      timestamptz not null default now(),
  created_by      uuid        not null references auth.users (id),

  -- Revocation is the whole safety story of a shareable link, so it is a column rather than a
  -- delete: a business wants to see that a link existed and was withdrawn.
  revoked_at      timestamptz,

  constraint customer_portal_invites_customer_same_org
    foreign key (organization_id, customer_id)
    references public.customers (organization_id, id) on delete cascade
);

comment on table public.customer_portal_invites is
  'A link a business sends a customer. Anyone holding it is that customer -- the model of a shared document link -- and the business revokes it.';

-- **The second index in this schema that is not led by `organization_id`, and it is the same
-- reason as the first.** An identifier the outside world *presents* must be resolvable without
-- already knowing which tenant it belongs to; an identifier the inside world *uses* is scoped
-- by the tenant that owns it. `external_actors_one_tenant_per_user` and this one are both the
-- former. `schema-conformance.test.ts` names both, with this rule rather than a pattern.
create unique index customer_portal_invites_token_unique
  on public.customer_portal_invites (token);

create index customer_portal_invites_org_customer_idx
  on public.customer_portal_invites (organization_id, customer_id);

alter table public.customer_portal_invites enable row level security;
alter table public.customer_portal_invites force row level security;

-- Only the business sees its invitations. An outsider never reads this table at all -- they
-- present a token to a function, and the function answers by writing a binding.
create policy customer_portal_invites_select on public.customer_portal_invites
  for select to authenticated
  using (organization_id in (select app.current_tenant_ids()));

create policy customer_portal_invites_insert on public.customer_portal_invites
  for insert to authenticated
  with check (
    organization_id in (select app.current_tenant_ids())
    and created_by = (select auth.uid())
    and app.has_capability(organization_id, 'customer.create')
  );

create policy customer_portal_invites_update on public.customer_portal_invites
  for update to authenticated
  using (
    organization_id in (select app.current_tenant_ids())
    and app.has_capability(organization_id, 'customer.create')
  )
  with check (
    organization_id in (select app.current_tenant_ids())
    and app.has_capability(organization_id, 'customer.create')
  );

grant select, insert on public.customer_portal_invites to authenticated;
-- Revoking only. Nothing may move an invitation to a different customer, which would hand
-- whoever already holds the link somebody else's history.
grant update (revoked_at) on public.customer_portal_invites to authenticated;

create function public.create_portal_invite(p_customer_id uuid)
returns text
language plpgsql
volatile
set search_path = ''
as $fn$
declare
  v_actor    uuid := (select auth.uid());
  v_customer public.customers;
  -- Two v4 uuids, hyphens stripped: 64 hex characters and 256 bits of randomness, from a
  -- built-in rather than from pgcrypto. `gen_random_bytes` would have been the obvious call
  -- and would have made this migration depend on an extension being installed in a schema the
  -- function can see -- which, with `search_path` pinned empty, it cannot without qualifying.
  v_token    text := replace(gen_random_uuid()::text, '-', '')
                  || replace(gen_random_uuid()::text, '-', '');
begin
  if v_actor is null then
    raise exception 'create_portal_invite requires an authenticated caller'
      using errcode = '42501';
  end if;

  select * into v_customer from public.customers where id = p_customer_id;

  if v_customer.id is null then
    raise exception 'no such customer, or you may not invite them'
      using errcode = '42501';
  end if;

  insert into public.customer_portal_invites (organization_id, customer_id, token, created_by)
  values (v_customer.organization_id, p_customer_id, v_token, v_actor);

  insert into public.events
    (organization_id, actor_id, entity_type, entity_id, action, payload)
  values
    (v_customer.organization_id, v_actor, 'customer', p_customer_id, 'customer.portal_invited',
     jsonb_build_object('customer_id', p_customer_id));

  -- The token is returned once, to the operator who made it. It is stored so it can be
  -- checked and revoked, and shown again on the customer's screen because a business that
  -- loses the link it sent has to be able to send it again -- this is a shareable link, not a
  -- password, and pretending otherwise would only mean issuing a second one.
  return v_token;
end;
$fn$;

revoke all on function public.create_portal_invite(uuid) from public;
grant execute on function public.create_portal_invite(uuid) to authenticated;

-- ---------------------------------------------------------------------------
-- Claiming one
-- ---------------------------------------------------------------------------

-- `external_actors` gains the column D22 predicted, and it is written by **nothing but the
-- function below**. There is no column grant for it and no update policy on the table, so the
-- attack that removed it in the first place -- an outsider writing somebody else's customer id
-- onto their own binding -- is still impossible.
alter table public.external_actors
  add column customer_id uuid,
  add constraint external_actors_customer_same_org
    foreign key (organization_id, customer_id)
    references public.customers (organization_id, id) on delete set null (customer_id);

comment on column public.external_actors.customer_id is
  'Which customer this outsider is, when a business has said so by sending them a link. Written only by claim_portal_invite; in no column grant.';

create function app.current_external_customer()
returns uuid
language sql
stable
security definer
set search_path = ''
as $fn$
  select ea.customer_id
  from public.external_actors ea
  where ea.user_id = (select auth.uid());
$fn$;

comment on function app.current_external_customer() is
  'The customer an outsider has been recognised as, or null. Companion to app.current_external_tenant(); both answer about one caller and neither returns a set.';

revoke all on function app.current_external_customer() from public;
grant execute on function app.current_external_customer() to authenticated;

-- SECURITY DEFINER, and the token is the authorization. The caller arrives with an anonymous
-- session and no binding, so there is nothing for RLS to key on yet -- the same chicken-and-egg
-- `booking_organization` breaks, answered the same way: privileged, narrow, and it says nothing
-- back except whether it worked.
create function public.claim_portal_invite(p_token text)
returns uuid
language plpgsql
volatile
security definer
set search_path = ''
as $fn$
declare
  v_actor  uuid := (select auth.uid());
  v_invite public.customer_portal_invites;
begin
  if v_actor is null then
    raise exception 'claim_portal_invite requires an authenticated caller'
      using errcode = '42501';
  end if;

  select * into v_invite
  from public.customer_portal_invites
  where token = p_token
    and revoked_at is null;

  -- One message for "no such link" and "withdrawn". Telling them apart would let somebody
  -- holding a revoked link learn that it was once real.
  if v_invite.id is null then
    raise exception 'that link is not valid'
      using errcode = '42501';
  end if;

  -- **A binding is still exactly one tenant.** Somebody who has already booked with another
  -- business, or with this one anonymously, cannot be promoted into this customer -- the unique
  -- index on `user_id` refuses the insert, and the update below only ever touches a binding
  -- that already names this organization.
  insert into public.external_actors (organization_id, user_id, customer_id)
  values (v_invite.organization_id, v_actor, v_invite.customer_id)
  on conflict (user_id) do update
    set customer_id = excluded.customer_id
  where public.external_actors.organization_id = v_invite.organization_id;

  if not found then
    raise exception 'this browser is already booking with another business'
      using errcode = '42501';
  end if;

  return v_invite.organization_id;
end;
$fn$;

revoke all on function public.claim_portal_invite(text) from public;
grant execute on function public.claim_portal_invite(text) to authenticated;

-- ---------------------------------------------------------------------------
-- What a recognised customer may see
-- ---------------------------------------------------------------------------

-- **Rows I made, or rows about me.** The booking half of each policy is unchanged; the portal
-- adds the second clause. Both are permits, and neither consults a capability, because there is
-- still no role out here.
drop policy work_items_select_external on public.work_items;
create policy work_items_select_external on public.work_items
  for select to authenticated
  using (
    organization_id = app.current_external_tenant()
    and (
      created_by = (select auth.uid())
      or customer_id = app.current_external_customer()
    )
  );

drop policy customers_select_external on public.customers;
create policy customers_select_external on public.customers
  for select to authenticated
  using (
    organization_id = app.current_external_tenant()
    and (
      created_by = (select auth.uid())
      or id = app.current_external_customer()
    )
  );

drop policy work_item_priced_lines_select_external on public.work_item_priced_lines;
create policy work_item_priced_lines_select_external on public.work_item_priced_lines
  for select to authenticated
  using (
    organization_id = app.current_external_tenant()
    and work_item_id in (
      select w.id
      from public.work_items w
      where w.organization_id = public.work_item_priced_lines.organization_id
        and (
          w.created_by = (select auth.uid())
          or w.customer_id = app.current_external_customer()
        )
    )
  );

-- What they owe, and what they have paid. An invoice is a document this customer holds; a
-- portal that could not show it would be a list of jobs with no money in it.
create policy invoices_select_external on public.invoices
  for select to authenticated
  using (
    organization_id = app.current_external_tenant()
    and customer_id = app.current_external_customer()
  );

create policy invoice_lines_select_external on public.invoice_lines
  for select to authenticated
  using (
    organization_id = app.current_external_tenant()
    and invoice_id in (
      select i.id
      from public.invoices i
      where i.organization_id = public.invoice_lines.organization_id
        and i.customer_id = app.current_external_customer()
    )
  );

create policy payments_select_external on public.payments
  for select to authenticated
  using (
    organization_id = app.current_external_tenant()
    and invoice_id in (
      select i.id
      from public.invoices i
      where i.organization_id = public.payments.organization_id
        and i.customer_id = app.current_external_customer()
    )
  );

-- **I19's second shape, and D20 named it in advance**: "a customer downloading their own
-- contract needs a signed URL minted after a permission check that has no `has_capability` to
-- call." This is that check. The metadata row is read under this policy first and the object is
-- signed for sixty seconds afterwards, exactly as `getDocumentUrl` already does for a member --
-- the permission check *is* the read, and there is no second path to the bytes.
create policy documents_select_external on public.documents
  for select to authenticated
  using (
    organization_id = app.current_external_tenant()
    and customer_id = app.current_external_customer()
  );
