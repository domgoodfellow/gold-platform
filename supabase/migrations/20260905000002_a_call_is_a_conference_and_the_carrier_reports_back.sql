-- Nothing else. No select, no insert, on any table. Everything this role can do is the one
-- function granted at the bottom, and everything that function writes is fixed in its body
-- rather than chosen by its caller -- which is what makes a forged callback unable to reach
-- past the call it names.

-- ---------------------------------------------------------------------------
-- record_call_event
-- ---------------------------------------------------------------------------

-- **The caller names no organization**, exactly as `record_provider_payment` names no invoice.
-- It supplies a carrier identifier; the tenant is derived from the row that identifier already
-- belongs to. A callback for a call this platform never placed finds nothing and writes nothing,
-- which is the behaviour that makes an unauthenticated retry harmless and a forged one useless.
create function public.record_call_event(
  p_external_id   text,
  p_source        text,
  p_raw_status    text,
  p_status        text,
  p_duration      integer,
  p_recording_url text,
  p_payload       jsonb,
  p_payload_hash  text
)
returns uuid
language plpgsql
volatile
security definer
set search_path = ''
as $fn$
declare
  v_actor  constant uuid := '00000000-0000-4000-8000-0000000000a2';
  v_call   public.calls;
  v_leg    public.call_participants;
  v_id     uuid;
begin
  -- The identifier is either the call's own or one of its legs'. Both are looked up because a
  -- conference reports per leg and a simple call reports as itself, and a handler that had to
  -- know which kind it was holding would be the carrier's model leaking one level up.
  select c.* into v_call
    from public.calls c
   where c.external_id = p_external_id;

  if not found then
    select p.* into v_leg
      from public.call_participants p
     where p.external_id = p_external_id;

    if not found then
      -- Nothing to attach to. Not an error: a callback can arrive for a call placed by another
      -- deployment sharing the carrier account, and refusing loudly would fill the log with
      -- somebody else's traffic.
      return null;
    end if;

    select c.* into v_call
      from public.calls c
     where c.organization_id = v_leg.organization_id
       and c.id = v_leg.call_id;
  end if;

  -- The retry guard. `on conflict do nothing` rather than a prior select, so two deliveries
  -- racing each other resolve in the index rather than in application logic.
  insert into public.call_events
    (organization_id, call_id, source, raw_status, payload, payload_hash)
  values
    (v_call.organization_id, v_call.id, p_source, p_raw_status,
     coalesce(p_payload, '{}'::jsonb), p_payload_hash)
  on conflict (organization_id, payload_hash) do nothing
  returning id into v_id;

  if v_id is null then
    -- Already seen. Nothing is applied a second time, which is what stops a retried *completed*
    -- writing a second ending onto a call that already ended.
    return null;
  end if;

  -- The leg, when this was about one.
  if v_leg.id is not null then
    update public.call_participants
       set status    = coalesce(p_status, status),
           joined_at = case
                         when p_status = 'in_progress' and joined_at is null then now()
                         else joined_at
                       end,
           left_at   = case
                         when p_status in ('completed', 'failed', 'no_answer', 'busy')
                           then coalesce(left_at, now())
                         else left_at
                       end
     where id = v_leg.id;
  end if;

  -- The call itself. **A status only ever moves forward into an ending**: a late *ringing*
  -- arriving after *completed* must not reopen a finished call, and callbacks do arrive out of
  -- order.
  update public.calls
     set status           = case
                              when status in ('completed', 'failed', 'no_answer', 'busy')
                                then status
                              else coalesce(p_status, status)
                            end,
         duration_seconds = coalesce(p_duration, duration_seconds),
         recording_url    = coalesce(p_recording_url, recording_url),
         ended_at         = case
                              when p_status in ('completed', 'failed', 'no_answer', 'busy')
                                then coalesce(ended_at, now())
                              else ended_at
                            end
   where id = v_call.id;

  -- On the customer's timeline, and only for the ending. Every intermediate state would be four
  -- entries per call saying nothing a person wants to read.
  if p_status in ('completed', 'failed', 'no_answer', 'busy') then
    insert into public.events
      (organization_id, actor_id, entity_type, entity_id, action, payload)
    values
      (v_call.organization_id, v_actor, 'customer', v_call.customer_id, 'call.ended',
       jsonb_build_object('call_id', v_call.id, 'status', p_status, 'duration', p_duration));
  end if;

  return v_id;
end;
$fn$;

comment on function public.record_call_event(text, text, text, text, integer, text, jsonb, text) is
  'The only thing the voice_webhook role may do. Derives the organization from the call or leg named by the carrier identifier; the caller names none of it. A repeated payload is a no-op.';

revoke all on function public.record_call_event(text, text, text, text, integer, text, jsonb, text) from public;
grant execute on function public.record_call_event(text, text, text, text, integer, text, jsonb, text) to voice_webhook;

-- ---------------------------------------------------------------------------
-- Placing a call now creates a room and two legs
-- ---------------------------------------------------------------------------

-- The web app writes the call and its legs in one act, so a conference can never exist with
-- nobody recorded as being in it. `security invoker`: the policies on `calls` decide whether
-- this caller may, exactly as they did before -- this function adds no authority, it only makes
-- three writes atomic.
create function public.open_call(
  p_organization_id uuid,
  p_customer_id     uuid,
  p_conference_name text,
  p_from_number     text,
  p_to_number       text,
  p_agent_id        uuid
)
returns uuid
language plpgsql
volatile
set search_path = ''
as $fn$
declare
  v_id uuid;
begin
  insert into public.calls
    (organization_id, customer_id, direction, status, from_number, to_number,
     conference_name, created_by)
  values
    (p_organization_id, p_customer_id, 'outbound', 'ringing', p_from_number, p_to_number,
     p_conference_name, (select auth.uid()))
  returning id into v_id;

  insert into public.call_participants (organization_id, call_id, party, member_id)
  values (p_organization_id, v_id, 'agent', p_agent_id),
         (p_organization_id, v_id, 'customer', null);

  insert into public.events
    (organization_id, actor_id, entity_type, entity_id, action, payload)
  values
    (p_organization_id, (select auth.uid()), 'customer', p_customer_id, 'call.placed',
     jsonb_build_object('call_id', v_id, 'direction', 'outbound', 'to_number', p_to_number));

  return v_id;
end;
$fn$;

comment on function public.open_call(uuid, uuid, text, text, text, uuid) is
  'A room and the two people expected in it, written together. security invoker: the calls policies decide whether the caller may, and this adds no authority of its own.';

revoke all on function public.open_call(uuid, uuid, text, text, text, uuid) from public;
grant execute on function public.open_call(uuid, uuid, text, text, text, uuid) to authenticated;

-- The web app writes `conference_name` through `open_call`, so the column joins the grant.
grant insert (conference_name) on public.calls to authenticated;
