-- D38 as schema, and the other half of a call: what the carrier tells us afterwards.
--
-- The first reception slice could write a call down and could not learn anything about one. It
-- recorded whatever status the carrier returned at the instant of asking -- which is always
-- *ringing* -- and then never heard another word, so `ended_at` and `duration_seconds` stayed
-- null unless a person typed them. This migration is the receiving end.
--
-- **Three things arrive together because none of them is useful alone.** A conference with no
-- participants is a room nobody is in. Participants with no event stream are rows that never
-- change. An event stream with nowhere to apply itself is a log.

-- ---------------------------------------------------------------------------
-- A call is a conference
-- ---------------------------------------------------------------------------

-- The room's name at the carrier, and the only thing tying our row to their world for the
-- duration of the call. Generated by us rather than by them, because a participant has to be
-- added to a room that already has a name -- there is nothing to ask.
alter table public.calls add column conference_name text
  check (conference_name is null or length(btrim(conference_name)) between 1 and 128);

-- Null for a call written down after it happened on somebody's mobile, which never had a room.
-- I2: the tenant id leads.
create unique index calls_org_conference_unique
  on public.calls (organization_id, conference_name)
  where conference_name is not null;

-- Where the audio lives at the carrier. **Not a document yet, and the distinction is real**:
-- `documents` holds bytes in our own storage under a tenant-scoped path (I19), and this is a
-- remote address that needs our credentials to fetch. Pulling the bytes across is a separate
-- act with its own failure modes, and it gets its own slice rather than being smuggled into
-- this column's meaning.
alter table public.calls add column recording_url text
  check (recording_url is null or length(btrim(recording_url)) between 1 and 2048);

-- The target of the composite foreign keys below. Not written in the first reception slice
-- because nothing referenced a call yet, and a unique constraint with no referent is the
-- abstraction this repository refuses -- but it is what makes "a leg belongs to the same
-- business as its call" a database guarantee rather than a caller's good manners (I18).
alter table public.calls
  add constraint calls_org_id_unique unique (organization_id, id);

-- ---------------------------------------------------------------------------
-- call_participants -- one party's leg
-- ---------------------------------------------------------------------------

-- **Hold, transfer, merge and coaching are each one operation on one of these rows** (D38).
-- That is the entire reason the table exists, and it is why it exists before any of those four
-- is built: they are not four features, they are one structure with four verbs, and adding the
-- structure afterwards means rebuilding the dialer.
create table public.call_participants (
  id              uuid        primary key default gen_random_uuid(),
  organization_id uuid        not null references public.organizations (id) on delete cascade,
  call_id         uuid        not null,

  -- What this leg is *for*, which is a platform fact rather than a tenant word: the carrier and
  -- this code both have to know which leg to hold and which to hand over, and a business
  -- renaming *agent* to *closer* must not change that. What a business calls its people is a
  -- role on a membership, and it is a different question.
  party           text        not null check (party in ('agent', 'customer', 'supervisor')),

  -- The carrier's identifier for this leg specifically. A conference has one name and as many
  -- of these as there are people in the room.
  external_id     text        check (external_id is null or length(btrim(external_id)) between 1 and 128),

  status          text        not null default 'ringing'
                              check (status in (
                                'ringing', 'in_progress', 'completed',
                                'failed', 'no_answer', 'busy'
                              )),

  -- **A live fact, maintained rather than snapshotted**, and one of the few in this schema. It
  -- is what the carrier is doing to this leg right now, so it is written by the event stream and
  -- read by a screen; it is not a record of anything and nothing historical depends on it.
  on_hold         boolean     not null default false,

  -- Who this leg belongs to, when it belongs to somebody here. Null for the customer's leg and
  -- for an agent who has since left the business.
  member_id       uuid        references auth.users (id) on delete set null,

  joined_at       timestamptz,
  left_at         timestamptz,
  created_at      timestamptz not null default now(),

  constraint call_participants_call_same_org
    foreign key (organization_id, call_id)
    references public.calls (organization_id, id) on delete cascade,

  constraint call_participants_left_after_joined
    check (left_at is null or joined_at is null or left_at >= joined_at)
);

comment on table public.call_participants is
  'One party on one call. Hold, transfer, merge and supervision are each an operation on a row here -- see constraints.md D38.';

create index call_participants_org_call_idx
  on public.call_participants (organization_id, call_id, created_at);

-- I2. Partial because a leg the carrier has not named yet is a leg we are still waiting on.
create unique index call_participants_org_external_unique
  on public.call_participants (organization_id, external_id)
  where external_id is not null;

alter table public.call_participants enable row level security;
alter table public.call_participants force row level security;

create policy call_participants_select on public.call_participants
  for select to authenticated
  using (organization_id in (select app.current_tenant_ids()));

-- **No insert, update or delete policy for anybody signed in**, and that is the point rather
-- than an omission. A leg is created when a telephone rings and changed when the carrier says
-- so; a person typing one would be inventing a call that did not happen. Everything that writes
-- here goes through `record_call_event` below.

grant select on public.call_participants to authenticated;

-- ---------------------------------------------------------------------------
-- call_events -- what the carrier said, exactly once
-- ---------------------------------------------------------------------------

-- **The deduplication is the whole reason this is a table rather than a log line, and it is
-- copied deliberately from a system that ran a floor on it.** A carrier retries a callback it
-- believes was not acknowledged, so the same event arrives two and three times; without a
-- unique key on the payload itself, a retried *completed* writes a second ending onto a call
-- that already ended.
create table public.call_events (
  id              uuid        primary key default gen_random_uuid(),
  organization_id uuid        not null references public.organizations (id) on delete cascade,
  call_id         uuid        not null,

  -- Which callback this arrived on. Platform vocabulary describing our own endpoints, so a
  -- reader can tell a status update from a recording without parsing the payload.
  source          text        not null check (source in ('status', 'recording', 'inbound')),

  -- The carrier's own word for what happened, never a paraphrase (I25). Kept beside the
  -- normalised status rather than instead of it, because the day the two disagree the raw one
  -- is the evidence.
  raw_status      text        check (raw_status is null or length(btrim(raw_status)) <= 64),

  -- Everything they sent. A jsonb object rather than a text blob so a question about a call
  -- three months old is a query rather than an archaeology project.
  payload         jsonb       not null default '{}'::jsonb
                              check (jsonb_typeof(payload) = 'object'),

  -- A digest of the body as it arrived. The retry guard, and nothing else reads it.
  payload_hash    text        not null check (length(btrim(payload_hash)) between 1 and 128),

  occurred_at     timestamptz not null default now(),

  constraint call_events_call_same_org
    foreign key (organization_id, call_id)
    references public.calls (organization_id, id) on delete cascade
);

comment on table public.call_events is
  'Every callback the carrier sent about a call, kept once. The unique index on payload_hash is what makes a retried delivery a no-op rather than a second ending.';

-- I2, and the guard. Leading with the tenant id costs nothing here because the hash is already
-- unique across the world; it is led with anyway, so this table cannot become the exception
-- somebody points at later.
create unique index call_events_org_payload_hash_unique
  on public.call_events (organization_id, payload_hash);

create index call_events_org_call_idx
  on public.call_events (organization_id, call_id, occurred_at desc);

alter table public.call_events enable row level security;
alter table public.call_events force row level security;

-- Readable, for the same reason `automation_runs` is: when somebody asks why a call says what it
-- says, the answer is here. Not writable by anybody signed in, for the same reason as above.
create policy call_events_select on public.call_events
  for select to authenticated
  using (organization_id in (select app.current_tenant_ids()));

grant select on public.call_events to authenticated;

